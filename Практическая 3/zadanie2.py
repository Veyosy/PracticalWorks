# - создание списка
my_list = [1,2,3]
print(my_list)

# - изменяем первый элемент списка
my_list[0] = 100
print(my_list)
# - список моно изменять после создания


# - создаем кортеж
my_tuple = (1,2,3)
print(my_tuple)
# - кортеж не изменить, выдает ошибку
# - my_tuple[0]=100


# - создаем строку
my_string = "cat"
print(my_string)
# - строку не изменить по отдельным символам
# - my_string[0] = 'b'