# - Создаем список покупок
shopping_list = ["PS5", "RTX5090", "ASUS500HZ", "Iphone 18PM"]

# - Добавляем еще один продукт в конец списка
shopping_list.append("Чехол для айфона")

# - Выводим список
print(shopping_list)

# - Создаем множество из тех же продуктов
unique_items = set(shopping_list)

# - Выводим множество
print(unique_items)

# list хранит элементы по порядку и может содержать повторы
# set хранит только уникальные значения